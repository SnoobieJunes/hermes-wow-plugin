-- Bundled scaffold checks for Guildhall (created 2026-11-11).
test('slash is registered', function(ctx)
    ctx.client:load_addon()
    assert_eq(ctx.client:eval("SLASH_GUILDHALL1"), "/gh")
end)
test('log stores a record', function(ctx)
    ctx.client:load_addon()
    assert_true(ctx.client:eval('Guildhall.Log.apply(Guildhall.Log.new(), {a = "A", s = 1, t = 1, k = "note", v = 1})'))
end)
test('window builds on first slash', function(ctx)
    ctx.client:load_addon()
    assert_false(ctx.client:eval('Guildhall.Window.built'))
    assert_eq(ctx.client:eval('Guildhall.Theme.name'), 'Classic')
    assert_true(ctx.client:slash("/gh"))
    assert_true(ctx.client:eval('Guildhall.Window.built'))
end)
